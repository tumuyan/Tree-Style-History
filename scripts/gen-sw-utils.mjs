// gen-sw-utils.mjs — generate `chrome/scripts/background-utils.js` from the
// shared bottom layer in `chrome/scripts/modules/shared/`.
//
// The Service Worker cannot load ES modules via `importScripts`, so the same
// functions that live in `modules/` (for the page scripts) must also exist as a
// classic script for `background-sw.js`. Instead of hand-maintaining a second
// copy (which drifts), we keep the dependency-free functions in `modules/
// shared/` as the single source of truth and mechanically flatten them into a
// classic script here.
//
// Usage:
//   node scripts/gen-sw-utils.mjs            # write background-utils.js
//   node scripts/gen-sw-utils.mjs --check    # exit 1 if it is stale

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { Script } from 'node:vm';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const SHARED_DIR = resolve(ROOT, 'chrome/scripts/modules/shared');
const OUT_FILE = resolve(ROOT, 'chrome/scripts/background-utils.js');

// Topological order. Must satisfy: a file only imports files listed before it.
// `validateFileList()` / `validateImportGraph()` enforce that this stays a
// complete, correctly ordered description of `modules/shared/`.
const FILES = [
    'config-defaults.js',
    'format.js',
    'url.js',
    'favicon.js',
    'calendar-storage.js'
];

const HEADER = `// ============================================================================
// GENERATED FILE — DO NOT EDIT BY HAND.
//
// This file is automatically generated by \`scripts/gen-sw-utils.mjs\` from the
// modules in \`chrome/scripts/modules/shared/\` (the dependency-free bottom
// layer). To change any function here, edit the corresponding shared module and
// run \`npm run gen\`, then commit the regenerated file.
//
// The shared modules are the single source of truth; this classic-script
// concatenation is what the Service Worker loads via importScripts.
// ============================================================================
`;

// A whole-line `import ... from '...';` / `import '...';`. Deliberately strict:
// a multi-line import must NOT match, so that it fails loudly instead of being
// half-stripped into syntactically valid but broken output.
const IMPORT_RE = /^\s*import\s+(?:[^'"\n]*?\sfrom\s+)?['"]([^'"]+)['"]\s*;?\s*$/;
// A whole-line `export { a, b, c };` — including the closing brace, so a block
// spanning several lines fails instead of losing only its first line.
// Both export forms carry a capture group so that `stripModuleSyntax()` (which
// only tests) and `collectExportedNames()` (which reads the name) match against
// literally the same pattern. Two spellings of one grammar is exactly the
// drift this generator exists to eliminate.
const EXPORT_BLOCK_RE = /^\s*export\s*\{([^}]*)\}\s*;?\s*$/;
const EXPORT_DECL_RE = /^\s*export\s+(?:async\s+)?(?:function|var|let|const|class)\s+([A-Za-z_$][\w$]*)/;

const UNSUPPORTED_HINT =
    'Only single-line `import ...;` and `export ...;` / `export { ... };` are flattened.';

/** Every `from './x.js'` specifier that appears on one line. */
function collectImports(src) {
    const out = [];
    for (const line of src.split(/\r?\n/)) {
        const m = IMPORT_RE.exec(line);
        if (m) out.push(m[1]);
    }
    return out;
}

/**
 * Names a module exports, in declaration order.
 *
 * Note `let`/`const`/`class` are included here even though ESLint's `exported`
 * directive comment does not honour them (see build()) — the shared layer
 * currently only uses `function` and `var`, and listing everything keeps the
 * two lists from drifting apart silently.
 */
function collectExportedNames(src) {
    const out = [];
    for (const line of src.split(/\r?\n/)) {
        const trimmed = line.trim();
        if (IMPORT_RE.test(trimmed)) continue;
        const decl = EXPORT_DECL_RE.exec(trimmed);
        if (decl) {
            out.push(decl[1]);
            continue;
        }
        const block = EXPORT_BLOCK_RE.exec(trimmed);
        if (block) {
            for (const part of block[1].split(',')) {
                // `a as b` is exported under `b`.
                const name = part.trim().split(/\s+as\s+/).pop().trim();
                if (name) out.push(name);
            }
        }
    }
    return out;
}

/**
 * FILES must name every module in `modules/shared/`, exactly once.
 *
 * Without this a newly added module would simply never reach the generated
 * file — no error, just a function the Service Worker cannot see.
 */
function validateFileList() {
    const onDisk = readdirSync(SHARED_DIR).filter((f) => f.endsWith('.js')).sort();
    const declared = new Set(FILES);
    const orphans = onDisk.filter((f) => !declared.has(f));
    if (orphans.length > 0) {
        throw new Error(
            `modules/shared/ contains file(s) missing from FILES in scripts/gen-sw-utils.mjs: ` +
            `${orphans.join(', ')}. Add them in dependency order or they will never be generated.`,
        );
    }
    const missing = FILES.filter((f) => !onDisk.includes(f));
    if (missing.length > 0) {
        throw new Error(
            `FILES in scripts/gen-sw-utils.mjs names file(s) that do not exist: ${missing.join(', ')}.`,
        );
    }
}

/**
 * Every local import must target a file that is flattened *earlier*.
 *
 * Import lines are deleted, not resolved. An import pointing at a file that is
 * absent from FILES (or ordered after the importer) would silently degrade into
 * an implicit global — syntactically fine, so the parse check below cannot see
 * it, and it only blows up at runtime in the Service Worker.
 */
function validateImportGraph(modules) {
    const order = new Map(FILES.map((f, i) => [f, i]));
    for (const { file, src } of modules) {
        for (const spec of collectImports(src)) {
            const target = spec.replace(/^\.\//, '');
            const targetIndex = order.get(target);
            if (targetIndex === undefined) {
                throw new Error(
                    `${file} imports '${spec}', which is not part of the generated bundle. ` +
                    `Add it to FILES (or drop the import — shared/ must stay dependency-free).`,
                );
            }
            if (targetIndex >= order.get(file)) {
                throw new Error(
                    `${file} imports '${spec}', but that file is flattened after it. ` +
                    `Reorder FILES so dependencies come first.`,
                );
            }
        }
    }
}

/**
 * Strip a single `import ... from '...';` statement (whole line) and the
 * `export` keyword from `export function/var/const/let/class` declarations.
 * A whole-line `export { a, b, ... };` block is dropped entirely.
 *
 * Any module syntax this does not recognise is a hard error: producing a file
 * that merely *looks* generated would defer the failure to Service Worker
 * load time, where it surfaces as a silently dead background script.
 *
 * Known limit: matching is line-based, so a line *inside* a template literal
 * that happens to read like a complete `import ...;` would also be stripped.
 * These modules are dependency-free string/date helpers, so it is not worth
 * a lexer — just do not put import-looking text in a template literal here.
 */
function stripModuleSyntax(line, file) {
    const trimmed = line.trim();
    if (IMPORT_RE.test(trimmed)) return null;
    if (/^\s*import\b/.test(trimmed)) {
        throw new Error(`Unsupported import syntax in ${file}: ${trimmed}\n${UNSUPPORTED_HINT}`);
    }
    if (EXPORT_BLOCK_RE.test(trimmed)) return null;
    if (EXPORT_DECL_RE.test(trimmed)) {
        return line.replace(/^(\s*)export\s+/, '$1');
    }
    if (/^\s*export\b/.test(trimmed)) {
        throw new Error(`Unsupported export syntax in ${file}: ${trimmed}\n${UNSUPPORTED_HINT}`);
    }
    return line;
}

function readModules() {
    validateFileList();
    const modules = FILES.map((file) => {
        const path = resolve(SHARED_DIR, file);
        if (!existsSync(path)) {
            throw new Error(`Shared source missing: ${path}`);
        }
        return { file, src: readFileSync(path, 'utf8') };
    });
    validateImportGraph(modules);
    return modules;
}

function build(modules) {
    const blocks = [HEADER.replace(/\n+$/, '')];

    // Declare the public surface for ESLint.
    //
    // background-sw.js reaches these through importScripts(), which static
    // analysis cannot see, so `no-unused-vars` would flag every symbol that is
    // not *also* called from inside this file (e.g. `getVersionType`).
    //
    // The list is derived from the modules' actual exports rather than
    // hand-written, so it cannot fall behind the way a manual list would.
    // ESLint only honours the directive for `function` and `var` declarations;
    // that is all modules/shared/ uses today.
    const exported = modules.flatMap((m) => collectExportedNames(m.src));
    if (exported.length > 0) {
        blocks.push(`/* exported ${exported.join(', ')} */`);
    }

    for (const { file, src } of modules) {
        const lines = [`// ---- begin modules/shared/${file} ----`];
        for (const line of src.split(/\r?\n/)) {
            const stripped = stripModuleSyntax(line, file);
            if (stripped === null) continue;
            lines.push(stripped);
        }
        lines.push(`// ---- end modules/shared/${file} ----`);
        blocks.push(lines.join('\n'));
    }
    // Normalise only the seams *between* blocks — trailing blank lines of each
    // file are dropped and exactly one blank line is inserted. Blank lines
    // inside a module are left alone: they may sit inside a template literal.
    return blocks.map((b) => b.replace(/\n+$/, '')).join('\n\n') + '\n';
}

const generated = build(readModules());

// The flattening is purely textual, so it can still yield something the parser
// rejects (a half-stripped multi-line import, say). Parse it here: better a
// failed `npm run gen` than a dead Service Worker.
try {
    new Script(generated, { filename: OUT_FILE });
} catch (error) {
    throw new Error(
        `Generated background-utils.js is not valid JavaScript: ${error.message}\n` +
        UNSUPPORTED_HINT,
    );
}

if (process.argv.includes('--check')) {
    if (!existsSync(OUT_FILE)) {
        console.error('FAIL: background-utils.js does not exist. Run `npm run gen`.');
        process.exit(1);
    }
    const current = readFileSync(OUT_FILE, 'utf8');
    if (current !== generated) {
        console.error('FAIL: chrome/scripts/background-utils.js is stale.');
        console.error('Run `npm run gen` and commit the result.');
        process.exit(1);
    }
    console.log('OK: background-utils.js is up to date.');
    process.exit(0);
}

writeFileSync(OUT_FILE, generated, 'utf8');
console.log('Generated chrome/scripts/background-utils.js');
